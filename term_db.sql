#SQL statement #1: How many Employees work at each branch
SELECT Branchid, COUNT(*) AS num_emp
FROM EMPLOYEE
GROUP BY Branchid;

#SQL statement #2: Show branches with more than 1 employees
SELECT Branchid, COUNT(*) AS num_emp
FROM EMPLOYEE
GROUP BY Branchid
HAVING COUNT(*) > 1;

#SQL Statement #3: Show Branch with the Most Assets
SELECT bn.Branchid, bn.Branchname, ba.Assets
FROM   branchname   AS bn
JOIN   branchassets AS ba ON ba.Branchid = bn.Branchid
WHERE  ba.Assets >= ALL (            -- same “>= ALL (…)” pattern as before
         SELECT Assets
         FROM   branchassets
       );

#SQL Statement #4: Show Customer with the Largest Bank Account Balance
SELECT SSN, Fullname
FROM CUSTOMER 
WHERE SSN IN (
    SELECT O.CustomerSSN
    FROM OPENACCOUNT O
    JOIN BANKACCOUNT B 
    ON O.Accountnumber = B.Accountnumber
    WHERE B.BALANCE >= ALL (
        SELECT BALANCE 
        FROM BANKACCOUNT
    )
); 



